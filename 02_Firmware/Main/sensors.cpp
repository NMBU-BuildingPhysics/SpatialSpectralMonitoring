void setupTSL2591() {
    if (!tsl.begin()) {
        Serial.println("TSL2591 initialize error.");
        while (1);
    }
    tsl.Enable();
    updateGain('I', I_gainValue);
    updateIntegrationTime('I', I_integrationTime);
}

void setupAS7331() {
    if (!as7331.begin()) {
        Serial.println("AS7331 initialize error.");
        while (1);
    }
    as7331.Set_Device_State(AS7331_STATE_CONFIGURATION);
    as7331.Set_Mode(AS7331_MMODE_CONT);
    as7331.Set_CCLK(AS7331_CCLK_1024);
    updateGain('U', U_gainValue);
    updateIntegrationTime('U', U_integrationTime);
    as7331.Set_BREAK(25);
    as7331.Set_Device_State(AS7331_STATE_MEASUREMENT);
    as7331.Set_Measurement(AS7331_MEASUREMENT_START);
}

